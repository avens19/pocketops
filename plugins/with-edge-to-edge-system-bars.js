const fs = require('node:fs');
const path = require('node:path');

const { withAndroidStyles } = require('expo/config-plugins');

/**
 * Stops Play Console reporting "deprecated APIs or parameters for edge-to-edge".
 *
 * `expo prebuild` writes `android:statusBarColor` and `android:navigationBarColor`
 * into `AppTheme`, both transparent. Android 15 (API 35) deprecated the pair and
 * ignores them when you target 35 or higher — which this app does, at 36 — so
 * Play flags them, and they do nothing for the users doing the flagging.
 *
 * Deleting them is the obvious move and the wrong one: `minSdkVersion` here is
 * 24, and on everything from Android 7 through 14 those attributes are honoured
 * and are exactly what makes the bars transparent under an edge-to-edge layout.
 * Strip them from the base theme and every pre-15 device gets opaque system bars
 * back, in exchange for a warning about devices that were never reading them.
 *
 * So the removal is qualified instead. The base `values/styles.xml` keeps them,
 * and a generated `values-v35/styles.xml` redefines `AppTheme` without them.
 * Android picks the most specific qualifier, so API 35+ gets the clean theme and
 * everything older is untouched. The v35 copy is built from the parsed base
 * style rather than hardcoded, so anything else the template adds to `AppTheme`
 * later comes along on its own.
 *
 * Note this file is generated at prebuild time and `android/` is gitignored —
 * editing `styles.xml` by hand would survive exactly until the next prebuild,
 * which is why this is a plugin and not a checked-in resource.
 */

const DEPRECATED_AT_API_35 = ['android:statusBarColor', 'android:navigationBarColor'];

const escapeXml = (value) =>
  String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

module.exports = function withEdgeToEdgeSystemBars(config) {
  return withAndroidStyles(config, (cfg) => {
    const styles = cfg.modResults?.resources?.style;
    if (!Array.isArray(styles)) return cfg;

    const appTheme = styles.find((style) => style?.$?.name === 'AppTheme');
    if (!appTheme || !Array.isArray(appTheme.item)) return cfg;

    const kept = appTheme.item.filter(
      (item) => !DEPRECATED_AT_API_35.includes(item?.$?.name),
    );
    // Nothing to qualify — the template stopped emitting them, so this plugin
    // has become a no-op and should not leave a stale override behind.
    if (kept.length === appTheme.item.length) return cfg;

    const items = kept
      .map(
        (item) =>
          `    <item name="${escapeXml(item.$.name)}">${escapeXml(item._)}</item>`,
      )
      .join('\n');

    const xml = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/with-edge-to-edge-system-bars.js. Do not edit.
  AppTheme without android:statusBarColor / android:navigationBarColor, which
  API 35 deprecated and ignores. The base values/styles.xml keeps them for
  API 24-34, where they still do the work.
-->
<resources>
  <style name="${escapeXml(appTheme.$.name)}" parent="${escapeXml(appTheme.$.parent)}">
${items}
  </style>
</resources>
`;

    const dir = path.join(
      cfg.modRequest.platformProjectRoot,
      'app/src/main/res/values-v35',
    );
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'styles.xml'), xml);

    return cfg;
  });
};
